def lookup_author(raw: str):
    """Ищет известного автора по любому слову в строке. Возвращает (имя, жанр) или None."""
    for token in raw.replace(".", " ").lower().split():
        if token in KNOWN_AUTHORS:
            return KNOWN_AUTHORS[token]
    return None


def guess(author: str) -> str:
    hit = lookup_author(author) if author else None
    return hit[1] if hit else "Другое"
